def test_the_prompt_no_longer_demands_a_reason_for_writing_again() -> None:
    """**禁止は命令に勝てない。** 直すのは手順のほうである。

    以前 STEP3 (3) は「それでもなお連絡したいと思った理由を一言で誠実に
    伝える」と命じていた。理由になる材料は渡していないので、モデルは理由を
    作った。検査を足すだけでは、別の言い回しの創作に変わるだけである。
    """
    # **命令として残っていないこと。** 語句そのものは、旧文言の引用として
    # プロンプトに残してある -- なぜこの形をやめたのかを次に読む人へ伝えるため
    # である。消すと教訓が消える。判定するのは命令の形のほうである。
    assert "恐縮を最初に述べ、そのうえで、それでもなお連絡したいと思った理由" not in _PROMPT
    assert "「度々のご連絡失礼いたします。」と **一言だけ** 述べる" in _PROMPT
    assert "理由を付け足さないこと" in _PROMPT
    # 旧文言は引用として残っている (教訓のため)。
    assert "と命じていた" in _PROMPT


def test_the_prompt_no_longer_offers_a_field_it_can_never_fill() -> None:
    """埋められない欄を渡さない。

    ``{{LAST_RESPONSE}}`` は常に「非公開」だった。「非公開」は「候補者が伏せて
    いる」とも読めるので、モデルは何か書いてよいと受け取りうる。**そもそも
    渡さないほうが誤解の余地が無い。**
    """
    assert "{{LAST_RESPONSE}}" not in _PROMPT
    assert "{{LAST_SENT_AT}}" not in _PROMPT
    assert "返事があったかどうかは、\nこの媒体からは一切分からない" in _PROMPT.replace("**", "")
